import * as React from "react"
import { cn } from "cn"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card flex min-w-0 flex-col overflow-hidden rounded-[26px] border border-frame-border bg-frame p-1 text-sm text-card-foreground shadow-[0_1px_2px_rgba(0,0,0,0.06)] [--card-spacing:--spacing(4)] [corner-shape:squircle] data-[size=sm]:[--card-spacing:--spacing(3)]",
        className
      )}
      {...props}
    />
  )
}

